"""Generate frozen Unicode 15.0 scalar-width policy; not a grapheme segmenter."""
from pathlib import Path
import unicodedata as ud

if ud.unidata_version != "15.0.0":
    raise SystemExit("Use Python with Unicode database 15.0.0 (tested Python 3.12.10)")


def width(cp):
    # Reject sequences whose display width needs grapheme/emoji presentation handling.
    if 0xFE00 <= cp <= 0xFE0F or 0xE0100 <= cp <= 0xE01EF or 0x1F3FB <= cp <= 0x1F3FF or 0x1F1E6 <= cp <= 0x1F1FF:
        return -1
    category = ud.category(chr(cp))
    if category in ("Mn", "Me"):
        return 0
    if category[0] in "LNPS" or category == "Zs":
        return 2 if ud.east_asian_width(chr(cp)) in ("W", "F") else 1
    return -1


ranges = []
for cp in range(0x110000):
    value = width(cp)
    if value < 0:
        continue
    if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == value:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, value])
header = '''// Generated by generate_width.py from Python unicodedata 15.0.0.
// Unicode data attribution and terms: UNICODE-LICENSE.txt.
#pragma once
#include <cstdint>
#include <iterator>
namespace termforge {
struct WidthRange { uint32_t first, last; int width; };
inline constexpr WidthRange width_ranges[] = {
'''
header += "".join(f"    {{0x{a:X}, 0x{b:X}, {w}}},\n" for a, b, w in ranges)
header += '''};
inline int scalar_width(uint32_t cp) {
    if (cp >= 32 && cp <= 126) return 1;
    size_t lo = 0, hi = std::size(width_ranges);
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        const auto& r = width_ranges[mid];
        if (cp < r.first) hi = mid;
        else if (cp > r.last) lo = mid + 1;
        else return r.width;
    }
    return -1;
}
} // namespace termforge
'''
Path(__file__).with_name("unicode_width.hpp").write_text(header, encoding="utf-8", newline="\n")
print(f"Generated {len(ranges)} ranges")
